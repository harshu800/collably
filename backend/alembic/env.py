"""Alembic migration environment.

Loads the sync psycopg2 URL from `app.core.config.Settings.database_url_sync`
(derived from the async asyncpg URL).
"""

from __future__ import annotations

from logging.config import fileConfig

from sqlalchemy import engine_from_config, pool

from alembic import context
from app.core.config import get_settings

# Alembic Config object; provides access to values within the .ini file in use.
config = context.config

# Interpret the config file for Python logging. This line sets up loggers.
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# Inject the DB URL from Settings (sync psycopg2 URL) so operators do not have
# to duplicate it in alembic.ini.
settings = get_settings()
config.set_main_option("sqlalchemy.url", settings.database_url_sync)

# Import DeclarativeBase + all models so metadata is populated for autogenerate.
# Migrations in this repo are hand-authored (not autogenerated), but we still
# wire this up so that future autogenerate runs would have complete metadata.
# Importing the models module registers them against Base.metadata.
from app import models  # noqa: F401, E402
from app.db.base import Base  # noqa: E402

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    """Run migrations in 'offline' mode (emits SQL to stdout)."""

    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations in 'online' mode (connects to the DB)."""

    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )

    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata)

        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
